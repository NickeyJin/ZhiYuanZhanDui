/*
arm.h —— 三自由度机械臂 + 夹爪（TIM4 四路 50Hz 舵机）

    肩 ch1 PB6 (TIM4_CH1)  行程约 30 度   实测 1072 ~ 1372 us
    肘 ch2 PB7 (TIM4_CH2)  行程约 145 度  实测  764 ~ 2372 us
    腕 ch3 PB8 (TIM4_CH3)  行程约 160 度  实测  620 ~ 2400 us
    爪 ch4 PB9 (TIM4_CH4)  行程约 70 度   实测  560 ~ 1340 us

    下面 ARM_US_* 就是这四个范围各往里收 10us 的结果 —— 别顶死在机械端上，
    顶住了舵机会堵转发烫。

=====================================================================
按键（不按 R2 = 点动模式）
=====================================================================
    ↑ / ↓      肩（大臂根，只有 30 度，一下就到头）
    ← / →      肘（大臂与小臂之间的弯折）
    △ / ×      腕（爪子朝上还是朝下）
    □ / ○      爪 张开 / 合上
    按住 L1    慢速点动（速度 1/3，调精确位置用）
    按住 R1    快速点动（速度 3 倍）
    SELECT+START  四路松劲 / 通电（松劲后可以用手随便掰）
                  注意：上电默认是松劲的，摆好位置后先按这一下才通电，
                  否则舵机一动会去追记忆里的位置，可能把你手扭到。

    R2 + R1     放块宏（见下）
    START       整车急停（底盘停 + 机械臂松劲）

    注意：这些都是"点动"，按住就一直走，松手就停在那个位置。

=====================================================================
上电初始位 / 放块位（都是编译期常量，改这里重新编译即可）
=====================================================================
    SELECT + START  上电：四路走到"初始位"（爪子闭合）—— 也就是每次
                    开机后机械臂该待的位置
    R2 + R1         放块宏，一按到底全自动（只在通电状态下有效）：
                    1) 先记下按下瞬间的四路姿态
                    2) 肩 / 肘 / 腕 走到"放块位"
                    3) 三路都到位后，爪子才张开，把方块丢下去
                       （张开保持 ARM_PUT_HOLD_MS，让方块落稳）
                    4) 四路回到按下 R2+R1 之前的姿态

    ★ 这两个位置是 2026-10-19 21:03 现场实测写死的：
      肩 1082 / 肘 2500 / 腕 2004（初始位爪子 570 = 完全闭合）
      要改位置就改下面的 define，重新编译烧录，不需要现场记录。

=====================================================================
要点：这套东西没有"模式"需要切，按住什么键就走什么动作
=====================================================================
    L2 目前是空键。
*/
#ifndef ARM_H
#define ARM_H

#include <stdint.h>

#define ARM_CH_N             4      /* 肩/肘/腕/爪 四路 */

/* ===================== 软限位（实测值内收 10us） ===================== */
#define ARM_US_SH_MIN    1082      /* 肩：2026-10-19 现场实测 1072=最高 / 1372=最低，内收 10us */
#define ARM_US_SH_MAX    1800      /* 肩向下：2026-10-19 现场放开（实测最低点 1372，用户手动放到 1800） */
#define ARM_US_EL_MIN      700      /* 肘：先放开一点，靠点动一点点试真边 */
#define ARM_US_EL_MAX     2500
#define ARM_US_WR_MIN      630      /* 腕 */
#define ARM_US_WR_MAX     2390
#define ARM_US_GR_MIN      570      /* 爪 */
#define ARM_US_GR_MAX     1330

/* ===================== 上电初始位（四路，爪子闭合） ===================== */
/* 2026-10-19 21:03 实测：钩爪完全闭合时点动到的"上电初始位"。
   SELECT+START 上电后四路走到这里。 */
#define ARM_US_INIT_SH    1082
#define ARM_US_INIT_EL    2500
#define ARM_US_INIT_WR    2004
#define ARM_US_INIT_GR     570      /* 爪子完全闭合 */

/* ===================== 放块位（前三个舵机） ===================== */
#define ARM_US_PUT_SH     1082
#define ARM_US_PUT_EL     2500
#define ARM_US_PUT_WR     2004
#define ARM_US_PUT_GR_OPEN 1330     /* 丢方块时爪子张开到多少（1330 = 全开） */
#define ARM_PUT_HOLD_MS    400      /* 张开后保持多久，让方块落稳 */
#define ARM_PUT_ARRIVE_US    8      /* "到位"判定：距目标 ≤8us */
#define ARM_PUT_TIMEOUT_MS 6000     /* 安全超时：超时不再等，直接进下一步 */

/* ===================== 点动速度（us 每秒） ===================== */
#define ARM_SPEED_SH      600
#define ARM_SPEED_EL      700
#define ARM_SPEED_WR      700
#define ARM_SPEED_GR      900

/* ===================== 解算 ===================== */
#define ARM_IK_MM_S       45        /* 方向键推着爪子移动的速度 mm/s */
#define ARM_IK_X_MIN     (-40.0f)   /* 肩轴前方的 x 范围（正 = 车头方向） */
#define ARM_IK_X_MAX      205.0f
#define ARM_IK_Y_MIN        5.0f    /* 爪口离地高度范围 */
#define ARM_IK_Y_MAX      250.0f

/* ===================== 对外接口 ===================== */
void arm_init(void);
void arm_task(void);
void arm_stop(void);                /* 目标就地停住（急停用） */

#endif /* ARM_H */
