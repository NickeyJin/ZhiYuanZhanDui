/*
app.h —— 应用层配置 + 主循环（PS2 手柄 → 麦轮底盘）

main() 里就调两个函数：
    app_init();               // 初始化一次
    while (1) app_task();     // 主循环反复调，内部自己按 20ms 走节拍

========================= 操作方式 =========================
上电就在驾驶状态，没有模式要切。

左摇杆 —— 只出 4 个方向，每个方向占 90° 扇区，不斜走：
    往前推   → 前进
    往后拉   → 后退
    往左推   → 左平移
    往右推   → 右平移
    扇区划分：比较 |横向| 和 |纵向|，谁大算谁（夹角 45° 为界 = 各占 90°）。
    斜着推的时候取"大的那个轴"，所以不会有"斜着走"这种中间态。

右摇杆左右 —— 原地自转（左推 = 左转，右推 = 右转）。
    转向完全靠自转，不用轮子差速，所以方向最准。

按住 L1  —— 慢速档：平移、自转、底盘全部减半（对位、贴目标时用）
START    —— 急停：四轮立刻停（机械臂也会一起松劲）

    —— 下面这几个是"调车"用的，平时不用碰，详见 tune.h ——
    SELECT + ↑ / ↓      前后配平旋钮（横移跑偏时调它，掉电保存）
    SELECT + ← / →      总速度 / 单轮补偿旋钮（按住肩上键选轮子）
    SELECT 相关的其他组合留给机械臂

灯（PC13）：
    常亮 = 手柄正常 / 快闪 = 正在按键 / 中闪 = 摇杆在动 /
    慢闪 300ms = 急停中 / 灭 = 手柄掉线

========================= 各文件分工 =========================
ps2.c        手柄通信（SPI 时序 + 切模拟模式）
chassis.c    麦轮运动学：vx / vy / omega → 四个轮子的转速
motor.c      单个电机的方向 + PWM（20kHz / 满速 40%）
tune.c       现场调参旋钮（前后配平 / 总速度 / 单轮补偿）
arm.c        机械臂（点动 / 上电初始位 / 放块宏）
app.c        主循环：读手柄 → 4 方向 → 斜坡 → 发给底盘
*/
#ifndef APP_H
#define APP_H

#include <stdint.h>

/* 主循环节拍，20ms = 50Hz，也是斜坡的最小时间粒度 */
#define APP_LOOP_MS           20

/* ===================== 平移速度 ===================== */

/* 快速档（默认）目标速度上限。<= CHASSIS_SPEED_MAX */
#define APP_SPEED_MAX         800

/* 慢速档（按住 L1）目标速度上限 */
#define APP_SPEED_SLOW        400

/* 起速补偿：摇杆一离开死区，速度就直接给到这个值，而不是从 0 慢慢爬。
   原因是这颗 TT 马达低占空比带不动，从 0 映射容易原地不动。
   嫌起步太猛就调小；设成 0 就是纯线性。 */
#define APP_SPEED_MIN         250

/* ===================== 自转速度 ===================== */

/*
自转（右摇杆左右）单独一套上下限，和翻译分开设：
    APP_TURN_MAX   摇杆推到底的自转速度
    APP_TURN_MIN   摇杆刚离开死区时的自转速度
为什么下限给得比平移高：原地自转要克服四个轮子的侧向摩擦，
占空比太低只会嗡鸣不转（实测低于约 30% 就转不动），所以一离开死区
就必须给足。嫌自转太冲就把 MAX 调小，但别低于 MIN。
按住 L1 时两个值都减半。
*/
#define APP_TURN_MAX          800
#define APP_TURN_MIN          400

/* ===================== 手势/斜坡 ===================== */

/* 加减速斜坡：从 0 升到 APP_SPEED_MAX 大约要这么多毫秒。
   调小反应快、容易冲出去；调大起步柔和、但显得迟钝。 */
#define APP_RAMP_MS           250

/* 死区：手柄回中不会精确停在 0x80，留点余量，也顺便滤掉手抖 */
#define APP_STICK_DEADZONE    12

/*
"前后配平"旋钮（按住 SELECT + ↑/↓）：↑ = 前一对轮子变快、后一对变慢。
每 250ms 一格 APP_TRIM_STEP（按住 L1 一格 20），最远 ±APP_TRIM_LIMIT。
方向：左移时车头顺时针转 → 按 ↑；逆时针转 → 按 ↓。
调好的值掉电保存，用 read_vars.ps1 读 t_trim_delta 能看到，然后抄进 tune.c 的默认值。
*/
#define APP_TRIM_STEP         5
#define APP_TRIM_LIMIT        300

void app_init(void);
void app_task(void);

#endif /* APP_H */
